import { useEffect, useRef, useState, type ChangeEvent, type FormEvent } from 'react'
import { ModalDialog } from './ModalDialog'
import { Icon } from './icons'
import { categories as defaultCategories } from '../data/categories'
import { saveLocalImageFile, deleteLocalImageFile, readLocalImageObjectURL, isOPFSSupported } from '../lib/opfsStorage'
import { extractDomain, normalizeUrl } from '../lib/localVaultStorage'
import type { CategoryRecord, CollectionRecord, InspirationRecord } from '../lib/storageTypes'

type InspirationFormModalProps = {
  open: boolean
  mode: 'add' | 'edit'
  initialRecord?: InspirationRecord | null
  existingRecords?: InspirationRecord[]
  collections?: CollectionRecord[]
  categories?: CategoryRecord[]
  initialCollectionId?: string
  onClose: () => void
  onSave: (recordData: {
    url: string
    title: string
    note: string
    categoryId: string
    tags: string[]
    favorite: boolean
    collectionId?: string
    imageFileName?: string
  }) => Promise<{ success: boolean; error?: Error }>
}

export function InspirationFormModal({
  open,
  mode,
  initialRecord,
  existingRecords = [],
  collections = [],
  categories = defaultCategories,
  initialCollectionId,
  onClose,
  onSave,
}: InspirationFormModalProps) {
  const [url, setUrl] = useState(() => (mode === 'edit' && initialRecord ? initialRecord.url : ''))
  const [title, setTitle] = useState(() => (mode === 'edit' && initialRecord ? initialRecord.title : ''))
  const [note, setNote] = useState(() => (mode === 'edit' && initialRecord ? initialRecord.note || '' : ''))
  const [categoryId, setCategoryId] = useState(() => (mode === 'edit' && initialRecord ? initialRecord.categoryId || 'other' : 'hero-sections'))
  const [collectionId, setCollectionId] = useState(() => {
    if (mode === 'edit' && initialRecord) {
      return initialRecord.collectionId || ''
    }
    return initialCollectionId || ''
  })
  const [tagsInput, setTagsInput] = useState(() => (mode === 'edit' && initialRecord ? initialRecord.tags.join(', ') : ''))
  const [favorite, setFavorite] = useState(() => (mode === 'edit' && initialRecord ? initialRecord.favorite : false))

  // Image handling
  const [selectedFile, setSelectedFile] = useState<File | null>(null)
  const [previewUrl, setPreviewUrl] = useState<string | null>(null)
  const existingImageFileName = mode === 'edit' && initialRecord ? initialRecord.imageFileName : undefined
  const [removeExistingImage, setRemoveExistingImage] = useState(false)

  // Validation & status
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [duplicateWarning, setDuplicateWarning] = useState<string | null>(null)
  const [titleWasAutoGenerated, setTitleWasAutoGenerated] = useState(false)
  const fileInputRef = useRef<HTMLInputElement>(null)

  // Load existing image if in edit mode
  useEffect(() => {
    let active = true
    if (mode === 'edit' && initialRecord?.imageFileName) {
      readLocalImageObjectURL(initialRecord.imageFileName).then((res) => {
        if (active && res.success) {
          setPreviewUrl(res.data)
        }
      })
    }
    return () => {
      active = false
    }
  }, [mode, initialRecord?.imageFileName])

  // Clean up object URLs on unmount or file change
  useEffect(() => {
    return () => {
      if (previewUrl && previewUrl.startsWith('blob:') && selectedFile) {
        URL.revokeObjectURL(previewUrl)
      }
    }
  }, [previewUrl, selectedFile])

  // Check for duplicate URLs on blur
  const handleUrlBlur = () => {
    if (!url.trim()) return
    const normalized = normalizeUrl(url)
    const duplicate = existingRecords.find(
      (r) =>
        r.url.toLowerCase() === normalized.toLowerCase() &&
        r.id !== initialRecord?.id,
    )

    if (duplicate) {
      setDuplicateWarning(
        `Note: "${duplicate.title}" is already saved with this URL. You can still save it if this is a different spark.`,
      )
    } else {
      setDuplicateWarning(null)
    }

    // Auto-fill the title only when it is still blank or still the generated default.
    const domain = extractDomain(normalized)
    const suggestedTitle = domain.charAt(0).toUpperCase() + domain.slice(1)

    if (!title.trim() || title === suggestedTitle || titleWasAutoGenerated) {
      setTitle(suggestedTitle)
      setTitleWasAutoGenerated(true)
    }
  }

  const handleTitleFocus = () => {
    if (titleWasAutoGenerated) {
      setTitle('')
      setTitleWasAutoGenerated(false)
    }
  }

  const handleFileChange = (e: ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0]
    if (!file) return

    // Validate size (max 8MB)
    if (file.size > 8 * 1024 * 1024) {
      setErrors((prev) => ({
        ...prev,
        image: 'Image file size must be less than 8MB.',
      }))
      return
    }

    // Validate type
    if (!file.type.startsWith('image/')) {
      setErrors((prev) => ({
        ...prev,
        image: 'Please select a valid image file (PNG, JPG, WebP, etc.).',
      }))
      return
    }

    setErrors((prev) => {
      const copy = { ...prev }
      delete copy.image
      return copy
    })

    setSelectedFile(file)
    setRemoveExistingImage(false)
    const localUrl = URL.createObjectURL(file)
    setPreviewUrl(localUrl)
  }

  const handleClearImage = () => {
    setSelectedFile(null)
    setPreviewUrl(null)
    setRemoveExistingImage(true)
    if (fileInputRef.current) {
      fileInputRef.current.value = ''
    }
  }

  const validate = (): boolean => {
    const newErrors: Record<string, string> = {}
    if (!url.trim()) {
      newErrors.url = 'Website URL is required.'
    } else {
      try {
        const normalized = normalizeUrl(url)
        new URL(normalized)
      } catch {
        newErrors.url = 'Please enter a valid web address (e.g. stripe.com or https://stripe.com).'
      }
    }

    if (!title.trim()) {
      newErrors.title = 'Title is required.'
    }

    setErrors(newErrors)
    return Object.keys(newErrors).length === 0
  }

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault()
    if (!validate()) return

    setIsSubmitting(true)

    try {
      let finalImageFileName = existingImageFileName

      // If user chose to remove the image
      if (removeExistingImage) {
        if (existingImageFileName) {
          await deleteLocalImageFile(existingImageFileName)
        }
        finalImageFileName = undefined
      }

      // If user uploaded a new local file
      if (selectedFile) {
        if (isOPFSSupported()) {
          const uploadRes = await saveLocalImageFile(selectedFile)
          if (uploadRes.success) {
            // Delete old image only after successful upload
            if (existingImageFileName && existingImageFileName !== uploadRes.data) {
              await deleteLocalImageFile(existingImageFileName)
            }
            finalImageFileName = uploadRes.data
          } else {
            setErrors((prev) => ({
              ...prev,
              image: `Local image storage warning: ${uploadRes.error.message}`,
            }))
            // Do not block record saving if image upload fails
          }
        }
      }

      const tags = tagsInput
        .split(',')
        .map((t) => t.trim().replace(/^#/, ''))
        .filter(Boolean)

      const res = await onSave({
        url: normalizeUrl(url),
        title: title.trim(),
        note: note.trim(),
        categoryId,
        tags,
        favorite,
        collectionId: collectionId || undefined,
        imageFileName: finalImageFileName,
      })

      if (res.success) {
        onClose()
      } else {
        setErrors((prev) => ({
          ...prev,
          form: res.error?.message || 'Could not save record to local storage.',
        }))
      }
    } catch (err) {
      setErrors((prev) => ({
        ...prev,
        form: err instanceof Error ? err.message : 'Unexpected save error.',
      }))
    } finally {
      setIsSubmitting(false)
    }
  }

  if (!open) return null

  return (
    <ModalDialog
      open={open}
      onClose={isSubmitting ? () => {} : onClose}
      labelledBy="inspiration-form-title"
      className="inspiration-form-dialog"
    >
      <div className="dialog__header">
        <div className="dialog__title-group">
          <p className="dialog__kicker">
            {mode === 'add' ? 'New Visual Reference' : 'Update Reference'}
          </p>
          <h2 id="inspiration-form-title" className="dialog__title">
            {mode === 'add' ? 'Add Inspiration' : 'Edit Inspiration'}
          </h2>
        </div>
        <button
          type="button"
          className="btn btn--ghost btn--icon dialog__close"
          onClick={onClose}
          disabled={isSubmitting}
          aria-label="Close dialog"
        >
          <Icon name="close" size={18} />
        </button>
      </div>

      <div className="dialog__body">
        {errors.form && (
          <div className="field__error field__error--banner" role="alert">
            {errors.form}
          </div>
        )}

        <form onSubmit={handleSubmit} className="inspiration-form" noValidate>
          {/* Website URL */}
          <div className={`field ${errors.url ? 'field--error' : ''}`}>
            <label htmlFor="form-website-url" className="field__label">
              <span>Website URL</span>
              <span className="field__optional">Required</span>
            </label>
            <input
              id="form-website-url"
              type="text"
              className="input"
              placeholder="e.g. stripe.com/press or https://linear.app"
              value={url}
              onChange={(e) => setUrl(e.target.value)}
              onBlur={handleUrlBlur}
              aria-invalid={Boolean(errors.url)}
              autoFocus={mode === 'add'}
              disabled={isSubmitting}
            />
            {errors.url && <p className="field__error">{errors.url}</p>}
            {duplicateWarning && (
              <p className="field__hint field__hint--warning">{duplicateWarning}</p>
            )}
          </div>

          {/* Title */}
          <div className={`field ${errors.title ? 'field--error' : ''}`}>
            <label htmlFor="form-title" className="field__label">
              <span>Inspiration Title</span>
              <span className="field__optional">Required</span>
            </label>
            <input
              id="form-title"
              type="text"
              className="input"
              placeholder="e.g. Glowing cursor interactions &amp; 3D hover"
              value={title}
              onChange={(e) => {
                setTitle(e.target.value)
                if (titleWasAutoGenerated) {
                  setTitleWasAutoGenerated(false)
                }
              }}
              onFocus={handleTitleFocus}
              aria-invalid={Boolean(errors.title)}
              disabled={isSubmitting}
            />
            {errors.title && <p className="field__error">{errors.title}</p>}
          </div>

          {/* Category & Favorite */}
          <div className="form-row-2">
            <div className="field">
              <label htmlFor="form-category" className="field__label">
                <span>Category</span>
              </label>
              <select
                id="form-category"
                className="select"
                value={categoryId}
                onChange={(e) => setCategoryId(e.target.value)}
                disabled={isSubmitting}
              >
                {categories.map((cat) => (
                  <option key={cat.id} value={cat.id}>
                    {cat.label}
                  </option>
                ))}
              </select>
            </div>

            <div className="field form-favorite-field">
              <label className="field__label" htmlFor="form-favorite-checkbox">
                <span>Favorite</span>
              </label>
              <label className="checkbox-toggle-label">
                <input
                  id="form-favorite-checkbox"
                  type="checkbox"
                  className="checkbox-toggle-input sr-only"
                  checked={favorite}
                  onChange={(e) => setFavorite(e.target.checked)}
                  disabled={isSubmitting}
                />
                <span className={`chip ${favorite ? 'chip--active' : ''}`}>
                  <Icon name="heart" size={14} />
                  <span>{favorite ? 'Marked as Favorite' : 'Add to Favorites'}</span>
                </span>
              </label>
            </div>
          </div>

          {/* Collection Assignment */}
          <div className="field">
            <label htmlFor="form-collection" className="field__label">
              <span>Collection</span>
              <span className="field__optional">Optional</span>
            </label>
            <select
              id="form-collection"
              className="select"
              value={collectionId}
              onChange={(e) => setCollectionId(e.target.value)}
              disabled={isSubmitting}
            >
              <option value="">No Collection (Ungrouped)</option>
              {collections.map((col) => (
                <option key={col.id} value={col.id}>
                  {col.name}
                </option>
              ))}
            </select>
          </div>

          {/* Notes */}
          <div className="field">
            <label htmlFor="form-note" className="field__label">
              <span>Why did you save it? (Reason / Notes)</span>
              <span className="field__optional">Recommended</span>
            </label>
            <textarea
              id="form-note"
              className="textarea"
              placeholder="e.g. Love the subtle teal glow on the buttons and the smooth 3D book hover animation."
              rows={3}
              value={note}
              onChange={(e) => setNote(e.target.value)}
              disabled={isSubmitting}
            />
          </div>

          {/* Tags */}
          <div className="field">
            <label htmlFor="form-tags" className="field__label">
              <span>Tags</span>
              <span className="field__optional">Comma-separated</span>
            </label>
            <input
              id="form-tags"
              type="text"
              className="input"
              placeholder="e.g. webgl, cards, glow, minimalist"
              value={tagsInput}
              onChange={(e) => setTagsInput(e.target.value)}
              disabled={isSubmitting}
            />
          </div>

          {/* Local Screenshot / Image Upload */}
          <div className="field">
            <span className="field__label">
              <span>Preview Screenshot</span>
              <span className="field__optional">Optional &middot; 100% Local (OPFS)</span>
            </span>

            {previewUrl ? (
              <div className="form-image-preview-box">
                <img src={previewUrl} alt="Preview" className="form-image-preview-box__img" />
                <button
                  type="button"
                  className="btn btn--destructive btn--sm form-image-preview-box__remove"
                  onClick={handleClearImage}
                  disabled={isSubmitting}
                >
                  <Icon name="trash" size={13} />
                  <span>Remove image</span>
                </button>
              </div>
            ) : (
              <div className="image-upload-dropzone">
                <input
                  ref={fileInputRef}
                  id="form-image-upload"
                  type="file"
                  accept="image/png,image/jpeg,image/webp,image/gif"
                  className="sr-only"
                  onChange={handleFileChange}
                  disabled={isSubmitting}
                />
                <label htmlFor="form-image-upload" className="image-upload-dropzone__label">
                  <Icon name="image" size={24} />
                  <span>Click to upload screenshot from your computer</span>
                  <span className="image-upload-dropzone__hint">PNG, JPG, WebP up to 8MB</span>
                </label>
              </div>
            )}
            {errors.image && <p className="field__error">{errors.image}</p>}
          </div>

          <div className="dialog__footer">
            <button
              type="button"
              className="btn btn--secondary"
              onClick={onClose}
              disabled={isSubmitting}
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn btn--primary"
              disabled={isSubmitting}
            >
              <Icon name="spark" size={15} />
              <span>
                {isSubmitting
                  ? 'Saving locally...'
                  : mode === 'add'
                  ? 'Save Inspiration'
                  : 'Update Inspiration'}
              </span>
            </button>
          </div>
        </form>
      </div>
    </ModalDialog>
  )
}
